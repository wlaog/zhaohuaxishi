test('verification uses preserved originals after input folders are removed, and still rejects changed inputs',async()=>{
  await fs.mkdir('qa-output/import-tests',{recursive:true});
  const project=path.resolve(await fs.mkdtemp('qa-output/import-tests/archive-')),root=path.join(project,'exports/LIFE');
  const id='n-1234567890abcdef12345678',folder='source/26/09/01',bytes=Buffer.from('第一段\n\n第二段\n');
  const store=await new DiaryStore(root).init();
  await store.save(id,{date:'2026-09-01',title:'Diary',revision:0,tags:[],blocks:[{id:'import-test',type:'text',html:'<p>第一段</p><p><br></p><p>第二段</p><p><br></p>'}]});
  await fs.writeFile(path.join(root,folder,'original.txt'),bytes);await fs.mkdir(path.join(root,'_imports'),{recursive:true});
  await fs.writeFile(path.join(root,'_imports/manifest.json'),JSON.stringify({sources:[{source:'日记/9.1.txt',originalPath:folder+'/original.txt',sha256:sha256(bytes),bytes:bytes.length,date:'2026-09-01',format:'txt',entryId:id,blockIds:['import-test'],assets:[]}]}));
  const report=await verifyImports({project,root});assert.equal(report.status,'PASS');assert.equal(report.archiveOnly,1);assert.equal(report.inputCompared,0);
  await fs.mkdir(path.join(project,'日记'));await fs.writeFile(path.join(project,'日记/9.1.txt'),'Changed source');
  const changed=await verifyImports({project,root});assert.equal(changed.status,'FAIL');assert.match(changed.errors[0].message,/输入原件哈希/);
});
